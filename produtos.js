// ==========================================
// ATUALIZAR PREÇO
// ==========================================

function atualizarPreco(index, categoria) {

    const produto = produtos[categoria][index];

    const select = document.getElementById("cor-" + index);

    if (categoria === "Máquinas") {

        const modalidade = select.value;

        document.getElementById("preco-" + index).textContent =
            produto.precos[modalidade];

        return;

    }

    const opcaoSelecionada = produto.cores[select.value];

    document.getElementById("preco-" + index).textContent =
        opcaoSelecionada.preco;

}


// ==========================================
// ADICIONAR AO CARRINHO
// ==========================================

function adicionarCarrinho(index, categoria) {

    const produto = produtos[categoria][index];

    const select = document.getElementById("cor-" + index);

    let opcaoSelecionada;

    if (categoria === "Máquinas") {

        const modalidade = select.value;

        const nomesModalidades = {
            comprar: "Compra",
            diaria: "Aluguel por diária",
            semanal: "Aluguel por semana"
        };

        opcaoSelecionada = {
            nome: nomesModalidades[modalidade],
            preco: produto.precos[modalidade]
        };

    } else {

        opcaoSelecionada = produto.cores[select.value];

    }

    if (!opcaoSelecionada || !opcaoSelecionada.preco) {

        alert("O preço desta opção ainda não foi cadastrado.");

        return;

    }

    const produtoExistente = carrinho.find(item =>
        item.nome === produto.nome &&
        item.opcao === opcaoSelecionada.nome
    );

    if (produtoExistente) {

        produtoExistente.quantidade++;

        produtoExistente.imagem =
            produtoExistente.imagem || produto.imagem;

        produtoExistente.categoria =
            produtoExistente.categoria || produto.categoria;

    } else {

        carrinho.push({

            nome: produto.nome,
            marca: produto.marca,
            categoria: categoria,
            opcao: opcaoSelecionada.nome,
            preco: opcaoSelecionada.preco,
            imagem: produto.imagem,
            quantidade: 1

        });

    }

    salvarCarrinho();

    atualizarContador();

    alert("Produto adicionado ao carrinho!");

}


