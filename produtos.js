// ==========================================

function atualizarContador() {

    const contador =
        document.getElementById("contador-carrinho");

    if (!contador) {
        return;
    }

    let quantidadeTotal = 0;

    carrinho.forEach(item => {
        quantidadeTotal += Number(item.quantidade) || 0;
    });

    contador.textContent = quantidadeTotal;

}


