// ==========================================
// CALCULAR SUBTOTAL
// ==========================================

function calcularSubtotal(item) {

    const preco = converterPreco(item.preco);

    const subtotal = preco * Number(item.quantidade);

    return formatarPreco(subtotal);

}


// ==========================================
// CALCULAR TOTAL
// ==========================================

function calcularTotal() {

    let total = 0;

    carrinho.forEach(item => {

        const preco = converterPreco(item.preco);

        total += preco * Number(item.quantidade);

    });

    return formatarPreco(total);

}


// ==========================================
// CONVERTER PREÇO
// ==========================================

function converterPreco(preco) {

    return Number(
        String(preco)
            .replace("R$", "")
            .replace(/\./g, "")
            .replace(",", ".")
            .trim()
    ) || 0;

}


// ==========================================
// FORMATAR PREÇO
// ==========================================

function formatarPreco(valor) {

    return valor.toLocaleString(
        "pt-BR",
        {
            style: "currency",
            currency: "BRL"
        }
    );

}


// ==========================================
// AUMENTAR QUANTIDADE
// ==========================================

function aumentarQuantidade(index) {

    if (!carrinho[index]) {
        return;
    }

    carrinho[index].quantidade++;

    salvarCarrinho();

    abrirCarrinho();

}


// ==========================================
// DIMINUIR QUANTIDADE
// ==========================================

function diminuirQuantidade(index) {

    if (!carrinho[index]) {
        return;
    }

    if (carrinho[index].quantidade > 1) {

        carrinho[index].quantidade--;

    } else {

        carrinho.splice(index, 1);

    }

    salvarCarrinho();

    abrirCarrinho();

}


// ==========================================
// REMOVER PRODUTO
// ==========================================

function removerCarrinho(index) {

    carrinho.splice(index, 1);

    salvarCarrinho();

    abrirCarrinho();

}


// ==========================================
// FINALIZAR PEDIDO PELO WHATSAPP
// ==========================================

function comprarCarrinhoWhatsApp() {

    if (carrinho.length === 0) {

        alert("Seu carrinho está vazio!");

        return;

    }

    const numero = "5512988660405";

    let mensagem =
        "Olá! Gostaria de fazer um pedido com a AJR:\n\n";

    carrinho.forEach((item, index) => {

        mensagem +=
            (index + 1) + ". " + item.nome + "\n" +
            "Marca: " + (item.marca || "") + "\n" +
            "Categoria: " + (item.categoria || "") + "\n" +
            "Opção: " + (item.opcao || "") + "\n" +
            "Quantidade: " + item.quantidade + "\n" +
            "Preço unitário: " + item.preco + "\n" +
            "Subtotal: " + calcularSubtotal(item) + "\n\n";

    });

    mensagem +=
        "TOTAL DO PEDIDO: " + calcularTotal() + "\n\n" +
        "Gostaria de confirmar a disponibilidade e finalizar o pedido ou a locação.";

    const link =
        "https://wa.me/" +
        numero +
        "?text=" +
        encodeURIComponent(mensagem);

    window.open(link, "_blank");

}


